// Embeds .open-next/assets into the Worker bundle and generates an entry that serves them.
//
// Why: from the Claude cloud session, `wrangler deploy` cannot upload Workers static assets:
// the asset-upload endpoint authenticates with a short-lived JWT in the Authorization header,
// and the session's egress proxy replaces that header with the stored Cloudflare API token
// (→ 401). The OpenNext asset set is small (~1.3 MiB, ~20 files), so we embed it in the
// Worker instead and provide an `ASSETS`-compatible shim. See docs/HOSTING.md and ADR-020.
//
// Usage: node scripts/cf-embed-assets.mjs   (after `npm run cf:build`)
// Then:  npx wrangler deploy -c wrangler.embedded.jsonc
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, extname } from "node:path";

const ROOT = ".open-next/assets";
const TYPES = {
  ".js": "application/javascript; charset=utf-8",
  ".mjs": "application/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".html": "text/html; charset=utf-8",
  ".json": "application/json",
  ".txt": "text/plain; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".ico": "image/x-icon",
  ".woff2": "font/woff2",
  ".map": "application/json",
};

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = walk(ROOT);
let total = 0;
const entries = files.map((f) => {
  const buf = readFileSync(f);
  total += buf.length;
  const path = "/" + relative(ROOT, f).split("\\").join("/");
  const type = TYPES[extname(f)] ?? "application/octet-stream";
  return `  ${JSON.stringify(path)}: { type: ${JSON.stringify(type)}, b64: ${JSON.stringify(buf.toString("base64"))} },`;
});

writeFileSync(
  ".open-next/embedded-assets.mjs",
  `// GENERATED by scripts/cf-embed-assets.mjs — do not edit.\nexport const ASSETS = {\n${entries.join("\n")}\n};\n`,
);

writeFileSync(
  ".open-next/entry.mjs",
  `// GENERATED by scripts/cf-embed-assets.mjs — Worker entry serving embedded static assets.
import worker from "./worker.js";
import { ASSETS } from "./embedded-assets.mjs";
export * from "./worker.js";

const cache = new Map();
function bytes(a) {
  let b = cache.get(a);
  if (!b) {
    const bin = atob(a.b64);
    b = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) b[i] = bin.charCodeAt(i);
    cache.set(a, b);
  }
  return b;
}
function serve(req) {
  const url = new URL(typeof req === "string" ? req : req.url);
  const a = ASSETS[decodeURIComponent(url.pathname)];
  if (!a) return new Response("Not found", { status: 404 });
  const immutable = url.pathname.startsWith("/_next/static/");
  return new Response(bytes(a), {
    headers: {
      "content-type": a.type,
      "cache-control": immutable ? "public, max-age=31536000, immutable" : "public, max-age=0, must-revalidate",
    },
  });
}
const assetsShim = { fetch: async (req) => serve(req) };

export default {
  ...worker,
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    if ((request.method === "GET" || request.method === "HEAD") && ASSETS[url.pathname] && !url.pathname.startsWith("/cdn-cgi/")) {
      return serve(request);
    }
    return worker.fetch(request, { ...env, ASSETS: assetsShim }, ctx);
  },
};
`,
);

console.log(`[cf-embed-assets] embedded ${files.length} files (${(total / 1024).toFixed(0)} KiB) → .open-next/entry.mjs`);
